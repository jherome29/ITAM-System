import {
  BLACK,
  CONTENT_WIDTH,
  FONT_BOLD,
  FONT_REGULAR,
  PAGE,
  bufferize,
  createDoc,
  drawFormTitle,
  drawLabelledLine,
  drawMetaFields,
  drawRepublicHeader,
  drawSignatureBlock,
  drawTable,
  ensureSpace,
  roleDisplay,
} from './base-form.generator';
import { CICC_LOGO_PNG } from './cicc-logo';
import {
  formatPrintDate,
  formatPrintDateTime,
  type PrintMeta,
  type PrintableRecord,
} from '../record-print';

// SVC: Deliver and Support / Improve - a paper copy of a record, as proof beyond the digital one.
// CICC asked for a printout after every step. One layout serves requisitions, return / incident
// requests and repairs; only the middle (facts, items, notes) differs.

const LOGO_SIZE = 42;
const SECTION_GAP = 8;

/** A bold section label with a rule under it. Returns the y below it. */
function drawSectionLabel(
  doc: PDFKit.PDFDocument,
  label: string,
  y: number,
): number {
  y = ensureSpace(doc, y, 40);
  doc.font(FONT_BOLD).fontSize(8).fillColor(BLACK);
  doc.text(label, PAGE.margin, y, { width: CONTENT_WIDTH });
  y += 11;
  doc
    .moveTo(PAGE.margin, y)
    .lineTo(PAGE.width - PAGE.margin, y)
    .strokeColor('#888888')
    .lineWidth(0.5)
    .stroke();
  return y + 5;
}

/** A labelled paragraph as tall as its text needs, so a long reason cannot run over what follows. */
function drawNote(
  doc: PDFKit.PDFDocument,
  label: string,
  value: string,
  y: number,
): number {
  const width = CONTENT_WIDTH;
  doc.font(FONT_REGULAR).fontSize(8);
  const body = doc.heightOfString(value || '-', { width });
  y = ensureSpace(doc, y, Math.min(body, 120) + 22);
  doc.font(FONT_BOLD).fontSize(8).fillColor(BLACK);
  doc.text(`${label}:`, PAGE.margin, y, { width });
  y += 11;
  doc.font(FONT_REGULAR).fontSize(8);
  doc.text(value || '-', PAGE.margin, y, { width });
  return y + body + 6;
}

export async function generateRecordPrint(
  record: PrintableRecord,
  meta: PrintMeta,
): Promise<Buffer> {
  const doc = createDoc();
  let y = drawRepublicHeader(doc);
  doc.image(CICC_LOGO_PNG, PAGE.margin, PAGE.margin, { width: LOGO_SIZE });

  y = drawFormTitle(doc, record.title, 'Print No.', meta.printNumber, y);

  y = drawMetaFields(
    doc,
    [
      { label: 'Reference', value: record.reference },
      { label: 'Status', value: record.status },
      ...record.facts,
      { label: 'Printed', value: formatPrintDateTime(meta.printedAt) },
      {
        label: 'Printed by',
        value: `${meta.printedBy.name}, ${roleDisplay(meta.printedBy.role)}`,
      },
    ],
    y,
  );

  if (meta.copy > 1) {
    y += 2;
    doc.font(FONT_BOLD).fontSize(8).fillColor(BLACK);
    const first = meta.firstPrintedAt
      ? `, first printed ${formatPrintDate(meta.firstPrintedAt)}`
      : '';
    doc.text(
      `REPRINT: copy ${meta.copy} of this record${first}.`,
      PAGE.margin,
      y,
      { width: CONTENT_WIDTH },
    );
    y += 14;
  }

  y += SECTION_GAP;
  if (record.table) {
    y = drawSectionLabel(doc, record.table.title, y);
    y = drawTable(doc, record.table.columns, record.table.rows, y);
  }

  for (const note of record.notes) y = drawNote(doc, note.label, note.value, y);

  if (record.events.length > 0) {
    y = drawSectionLabel(doc, 'WHAT HAPPENED, STEP BY STEP', y);
    const sorted = [...record.events].sort(
      (a, b) => a.at.getTime() - b.at.getTime(),
    );
    y = drawTable(
      doc,
      [
        { header: 'WHEN', width: 90 },
        { header: 'WHAT', width: 290 },
        { header: 'BY', width: 130 },
      ],
      sorted.map((e) => [formatPrintDateTime(e.at), e.what, e.by]),
      y,
    );
  }

  if (record.nextStep)
    y = drawLabelledLine(doc, 'Next step', record.nextStep, y);

  y = drawSignatureBlock(
    doc,
    record.signatories.map((s) => ({
      label: s.label,
      name: s.name,
      role: s.role,
      date: '',
    })),
    y + 12,
  );

  // The proof line: the number and code let anyone check this paper against the system.
  y = ensureSpace(doc, y, 34);
  doc.font(FONT_REGULAR).fontSize(7).fillColor('#444444');
  doc.text(
    `Verification code: ${meta.verificationCode}    Print No. ${meta.printNumber}    Record ${record.reference}`,
    PAGE.margin,
    y + 4,
    { width: CONTENT_WIDTH },
  );
  doc.text(
    'Computer-generated by AIMRS. Signatures are added by hand on this copy. Check this paper against the system with the print number and code above.',
    PAGE.margin,
    y + 15,
    { width: CONTENT_WIDTH },
  );

  return bufferize(doc);
}
